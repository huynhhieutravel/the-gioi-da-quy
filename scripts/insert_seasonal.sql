### Mâm cúng giao thừa trong nhà (Báo hiếu Tổ tiên & Gia Thần)
- Mâm cỗ mặn hoặc chay tùy theo truyền thống gia đình.
- Hoa tươi dâng bàn thờ: hoa cúc vàng kim, hoa lay ơn hoặc hoa cẩm chướng mang sinh khí tươi tắn.
